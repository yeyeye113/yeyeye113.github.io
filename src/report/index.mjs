// ---------------- 确定性选取 ----------------

function hashKey(key) {
  let h = 7;
  for (const ch of String(key)) h = (h * 31 + ch.codePointAt(0)) % 9973;
  return h;
}

function pick(pool, key) {
  return pool[hashKey(key) % pool.length];
}

// ---------------- 报告组装 ----------------

function quoteOf(text, max = 100) {
  const t = String(text ?? '').trim();
  if (t.length === 0) return '（未作答）';
  return t.length <= max ? t : `${t.slice(0, max)}……`;
}

function dimLine(radar, d) {
  const score = radar[d] ?? 0;
  return `- ${DIM_LABELS[d]}：${score} 分（${band(score)}档）。${pick(DIM_COMMENT[d][band(score)], `radar:${d}:${score}`)}`;
}

function buildQuestionSection(question, answer, score, index) {
  const dims = score?.dims ?? { structure: 0, relevance: 0, quantification: 0, depth: 0, clarity: 0 };
  const total = score?.total ?? 0;
  const weakDim = [...DIMS].sort((a, b) => dims[a] - dims[b] || DIMS.indexOf(a) - DIMS.indexOf(b))[0];
  const problems =
    (score?.evidence ?? []).length > 0
      ? score.evidence.slice(0, 3).map((e) => `  · [${DIM_LABELS[e.dim] ?? e.dim}] ${e.note}`).join('\n')
      : '  · 本题无明显扣分点，可作为你的标杆答案沉淀下来。';
  const fixes = [
    ...(score?.suggestions ?? []).slice(0, 2).map((s) => `  · ${s}`),
    `  · ${pick(DIM_FIX[weakDim], `${question.id}:fix:${total}`)}`,
  ].join('\n');
  const framework = pick(FRAMEWORK[question.type] ?? FRAMEWORK['行为'], `${question.id}:frame:${band(total)}`);
  const mustCover = Array.isArray(question.refPoints) && question.refPoints.length > 0
    ? ` 务必覆盖点：${question.refPoints.slice(0, 2).join('、')}。`
    : '';
  const dimBrief = DIMS.map((d) => `${DIM_LABELS[d]} ${dims[d]}`).join(' / ');

  const body = [
    `题目（${question.type}）：${question.text}`,
    `考察意图：${question.intent}`,
    `【你的回答】「${quoteOf(answer?.text)}」${answer?.followupText ? `（追问补答：「${quoteOf(answer.followupText, 60)}」）` : ''}`,
    `【得分】${total}/100（${dimBrief}）`,
    `【主要问题】\n${problems}`,
    `【怎么改】\n${fixes}`,
    `【参考回答框架】${framework}${mustCover}`,
  ].join('\n');

  return {
    heading: `③ 逐题诊断 · 第${index + 1}题`,
    body,
    locked: index !== 0,
  };
}

export function buildReport({ result, jd, resume, match }) {
  const plan = result?.plan ?? { questions: [] };
  const questions = Array.isArray(plan.questions) ? plan.questions : [];
  const answers = Array.isArray(result?.answers) ? result.answers : [];
  const scores = Array.isArray(result?.scores) ? result.scores : [];
  const ss = result?.sessionScore ?? {
    total: 0,
    radar: { structure: 0, relevance: 0, quantification: 0, depth: 0, clarity: 0 },
    weakest: [],
    strongest: [],
  };
  const total = ss.total ?? 0;
  const totalBand = band(total);
  const title = `《过面》模拟面试报告 · ${jd?.title ?? '目标岗位'}（${jd?.level ?? '未知'} · ${jd?.domain ?? '通用'}）`;
  const weakestLabels = (ss.weakest ?? []).map((d) => DIM_LABELS[d] ?? d).join('、') || '暂无';
  const strongestLabels = (ss.strongest ?? []).map((d) => DIM_LABELS[d] ?? d).join('、') || '暂无';
  const durationMin =
    Number.isFinite(result?.startedAt) && Number.isFinite(result?.endedAt) && result.endedAt > result.startedAt
      ? Math.round((result.endedAt - result.startedAt) / 60000)
      : null;
  const above70 = scores.filter((s) => (s?.total ?? 0) >= 70).length;

  const sections = [];

  // ① 总评与总分（免费）
  sections.push({
    heading: '① 总评与总分',
    body: [
      `本场共 ${questions.length} 道题${durationMin != null ? `，用时约 ${durationMin} 分钟` : ''}，总分 ${total}/100（${totalBand}档），其中 ${above70} 道题达到 70 分以上。`,
      pick(VERDICT[totalBand], `verdict:${total}:${questions.length}`),
      `最强项：${strongestLabels}；最需补强：${weakestLabels}。五维明细见雷达诊断，逐题的具体问题与改法见逐题诊断。`,
      `评分口径说明：本报告为本地规则评分（确定性启发式），衡量的是回答的结构、针对性、证据密度与表达质量，不等同于真实面试官的综合判断。`,
    ].join('\n'),
    locked: false,
  });

  // ② 五维雷达诊断（locked）
  sections.push({
    heading: '② 五维雷达诊断',
    body: [
      '五个维度按契约权重加权（结构化 25% / 相关性 25% / 深度 20% / 量化 15% / 清晰度 15%）：',
      ...DIMS.map((d) => dimLine(ss.radar ?? {}, d)),
      `读法提示：优先修最低分维度——同样一小时练习，花在「${weakestLabels}」上的分数回报最高。`,
    ].join('\n'),
    locked: true,
  });

  // ③ 逐题诊断（第一题免费，其余 locked）
  questions.forEach((question, i) => {
    sections.push(buildQuestionSection(question, answers[i], scores[i], i));
  });

  // ④ JD 匹配度与缺口（locked）
  const matchBody = match
    ? [
        `简历与该 JD 的匹配度：${match.matchScore ?? 0}/100。`,
        `已匹配的关键能力：${(match.matched ?? []).join('、') || '暂未识别'}。`,
        `明显缺口：${(match.missing ?? []).join('、') || '暂未识别'}。`,
        (match.missing ?? []).length > 0
          ? `缺口应对：对每个缺口技能准备一段「迁移性解释」——用最接近的已有经验说明你能多快补上，而不是回避。面试中被问到缺口时，先承认、再给学习路径、最后给相近佐证。`
          : '当前未发现显著技能缺口，重点转向经历深度的表达。',
        `岗位关键词全景：${(jd?.keywords ?? []).join('、') || '无'}。请核对本场回答对这些词的覆盖情况（见各题「主要问题」）。`,
      ].join('\n')
    : [
        '本场未提供简历匹配数据（未传入 resume/match），无法计算个人化匹配度。',
        `可以先对照岗位关键词自查：${(jd?.keywords ?? []).join('、') || '无'}。逐词问自己「我有没有一段能证明它的经历」，没有的词就是你的准备缺口。`,
        '建议下一场模拟前粘贴简历，报告将给出逐技能的匹配与缺口清单。',
      ].join('\n');
  sections.push({ heading: '④ JD 匹配度与缺口', body: matchBody, locked: true });

  // ⑤ 追问预演（locked）——V1.5 个性化：对准该题实际最弱维度＋未覆盖考点补位
  const followupLines = questions.map((q, i) => {
    const score = scores[i];
    const dims = score?.dims ?? { structure: 0, relevance: 0, quantification: 0, depth: 0, clarity: 0 };
    const ordered = [...DIMS].sort((a, b) => dims[a] - dims[b] || DIMS.indexOf(a) - DIMS.indexOf(b));
    const weakDim = ordered[0];
    const intro = pick(FOLLOWUP_INTRO, `${q.id}:intro`);
    const probe = pick(FOLLOWUP_BY_DIM[weakDim], `${q.id}:probe:${dims[weakDim]}`);
    const line1 = `第${i + 1}题（${q.type}）：本题最弱维度是「${DIM_LABELS[weakDim]}」（${dims[weakDim]} 分）。${intro}「${probe}」`;

    // 补位追问：优先从该题未覆盖的评分参考点生成（evidence 里的 relevance 扣分项可推）
    const gaps = (score?.evidence ?? [])
      .filter((e) => e.dim === 'relevance')
      .map((e) => {
        const m = /未覆盖评分参考点「(.+?)」/.exec(e.note);
        return m ? m[1] : null;
      })
      .filter(Boolean);
    let line2;
    if (gaps.length > 0) {
      const gap = gaps[hashKey(`${q.id}:gap:${gaps.length}`) % gaps.length];
      line2 = `  ↳ 考点补位：${pick(REFGAP_FOLLOWUP, `${q.id}:refgap`).replaceAll('{point}', gap)}`;
    } else {
      const second = ordered[1];
      line2 = `  ↳ 次弱维度（${DIM_LABELS[second]}，${dims[second]} 分）备防：「${pick(FOLLOWUP_BY_DIM[second], `${q.id}:probe2:${dims[second]}`)}」`;
    }
    return `${line1}\n${line2}`;
  });
  sections.push({
    heading: '⑤ 追问预演',
    body: [
      '按你每题的实际弱点生成：第 1 条打向该题得分最低的维度，第 2 条从未覆盖考点（或次弱维度）补位。逐条备好 50 字应答要点：',
      ...followupLines,
    ].join('\n'),
    locked: true,
  });

  // ⑥ 知识补强清单（locked）——V1.5 第一梯队：missing 技能逐个给 7 天最小学习闭环
  const enrichLines = [];
  const missingSkills = match?.missing ?? [];
  for (const skill of missingSkills.slice(0, 4)) {
    const key = String(skill).toLowerCase();
    const path = SKILL_PATHS[key]
      ?? pick(SKILL_PATH_GENERIC, `skillpath:${key}`).replaceAll('{skill}', String(skill));
    enrichLines.push(`- ${path}`);
  }
  const weakDims = (ss.weakest ?? []).length > 0 ? ss.weakest : ['structure'];
  for (const d of DIMS) {
    if (weakDims.includes(d) || (ss.radar?.[d] ?? 0) < 70) {
      enrichLines.push(`- ${pick(ENRICH[d], `enrich:${d}:${ss.radar?.[d] ?? 0}`)}`);
    }
  }
  if (enrichLines.length === 0) {
    enrichLines.push(`- ${pick(ENRICH[weakDims[0]] ?? ENRICH.structure, 'enrich:fallback')}`);
  }
  sections.push({
    heading: '⑥ 知识补强清单',
    body: [
      '第一梯队是 JD 缺口技能（每个给一条 7 天内可完成的最小学习闭环），第二梯队是本场暴露的表达弱项，逐条可执行、可勾选：',
      ...enrichLines,
    ].join('\n'),
    locked: true,
  });

  // ⑦ 7 天冲刺计划（locked）
  const sprintLines = SPRINT.map((dayPool, i) => `- ${pick(dayPool, `sprint:${i}:${total}:${weakestLabels}`)}`);
  sections.push({
    heading: '⑦ 7 天冲刺计划',
    body: ['以本场结果为起点的 7 天行动清单，每天一件事、每件事可验收：', ...sprintLines].join('\n'),
    locked: true,
  });

  // ⑧ 披露段（永不 locked、永在最后）
  sections.push({
    heading: '⑧ 披露与口径说明',
    body: [
      `${DISCLOSURE}。`,
      '本报告由本地确定性规则引擎生成（规则评分口径）：评分依据是回答文本的结构信号、考点覆盖、量化证据、思考深度与表达质量，不依赖联网，不上传你的简历与 JD。',
      '本产品不承诺任何面试结果，不代写简历，不提供背题式作弊内容；所有建议仅用于帮助你更完整地呈现真实经历。',
      '你的 JD、简历与作答内容只保存在本机，服务端不接收上述数据。',
    ].join('\n'),
    locked: false,
  });

  // ---- fullText：全文拼接 ----
  const fullText = [title, ...sections.map((s) => `${s.heading}\n${s.body}`)].join('\n\n');

  // ---- shareText：200-400 字，结尾必带披露句 ----
  const tail = `${DISCLOSURE}。`;
  let body =
    `【过面 · 模拟面试战报】${jd?.title ?? '目标岗位'}模拟面试完成：共 ${questions.length} 题，总分 ${total}/100（${totalBand}档）。` +
    `${SHARE_OPENERS[totalBand]}` +
    `本场最强项是${strongestLabels}，最需要补强的是${weakestLabels}，其中 ${above70} 道题达到 70 分以上。`;
  const pads = [
    '报告给出了逐题诊断、追问预演和一份 7 天冲刺计划，每条建议都落到可执行的具体动作上。',
    '接下来一周会按计划逐题重写低分回答、补齐量化数据，然后复测一场看雷达图的变化。',
    '面试是可以练的：把每段经历讲出结构、焊上数字，比临场发挥可靠得多。',
  ];
  let padIdx = 0;
  while ((body + tail).length < 200 && padIdx < pads.length) {
    body += pads[padIdx];
    padIdx += 1;
  }
  while ((body + tail).length < 200) {
    body += '每一场模拟的价值都在于把问题暴露在真实面试之前。';
  }
  if ((body + tail).length > 400) {
    body = `${body.slice(0, 400 - tail.length - 1)}。`;
  }
  const shareText = body + tail;

  return { title, sections, shareText, fullText };
}

export { DISCLOSURE };
