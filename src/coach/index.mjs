export function listCategories() {
  return [...CATEGORIES];
}

export function getTipsByCategory(category) {
  return TIPS.filter((t) => t.category === category);
}

export function searchTips(keyword) {
  const kw = typeof keyword === 'string' ? keyword.trim().toLowerCase() : '';
  if (!kw) return [];
  return TIPS.filter(
    (t) => t.title.toLowerCase().includes(kw) || t.body.toLowerCase().includes(kw),
  );
}

// 按评分弱维度 / 题型推荐 3-5 条（确定性：类别顺序按入参先后，类内按 TIPS 声明序轮转取条）
export function recommendTips({ weakDims = [], questionTypes = [] } = {}) {
  const cats = [];
  const pushCat = (c) => {
    if (c && !cats.includes(c)) cats.push(c);
  };
  for (const d of Array.isArray(weakDims) ? weakDims : []) pushCat(DIM_TO_CATEGORY[d]);
  for (const t of Array.isArray(questionTypes) ? questionTypes : []) pushCat(TYPE_TO_CATEGORY[t]);
  // 兜底：无有效入参时给「备考主干」三类（赛前准备→自我介绍→STAR实战）
  if (cats.length === 0) {
    pushCat('赛前准备');
    pushCat('自我介绍');
    pushCat('STAR实战');
  }
  const out = [];
  const seen = new Set();
  // 轮转取条：每轮从各类别取第 round 条，直到取满 5 条或全部耗尽（每类 ≥5 条，故必 ≥3 条）
  for (let round = 0; out.length < 5; round += 1) {
    let added = false;
    for (const c of cats) {
      if (out.length >= 5) break;
      const tip = getTipsByCategory(c)[round];
      if (tip && !seen.has(tip.id)) {
        seen.add(tip.id);
        out.push(tip);
        added = true;
      }
    }
    if (!added) break;
  }
  return out;
}
